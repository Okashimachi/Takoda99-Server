// RetiredEntries は h30 で辞書から外した語を WordEntry として返す。
//
// 用途は2つあり、どちらも「戻せること」のためにある:
//   - DB seed v3 の DELETE 対象（db.WordStore.Migrate）
//   - 旧辞書へ戻すときの再 upsert 対象（db.WordStore.RestoreRetired）
func RetiredEntries() []WordEntry {
	entries := make([]WordEntry, 0, 260)
	for lvl, words := range retiredWords {
		for _, text := range words {
			entries = append(entries, WordEntry{
				Text:           text,
				Reading:        text,
				KeystrokeCount: keystrokes(text),
				Level:          lvl,
				Category:       "general",
			})
		}
	}
	return entries
}
